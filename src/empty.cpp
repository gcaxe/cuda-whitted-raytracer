//  为什么需要它：
//    VS 的「C/C++ → 代码生成 → 运行库」这类属性，只有当项目里**存在真正的
//    .cpp 编译单元**时才会被实际使用。CUDA 项目里唯一的源文件通常是 kernel.cu，
//    它由 nvcc 驱动编译，C/C++ 页的设置**不会**作用到它身上 —— 于是想从 /MDd
//    切成 /MTd（为了匹配 assimp-vc142-mtd.lib 的静态运行库）时，改了也不生效。
//
//    放一个空的 .cpp，就让「C/C++」页的属性有了一个真正的消费者。
//
//  注意：
//    本文件**故意不含任何代码**。需要放「普通 C++ 实现」的地方请用别的文件
//    （例如 obj_assimp.cpp），不要把逻辑塞进来 —— 保持它的用途单一。
//
//  这个文件不参与任何逻辑，删掉也能编译 —— 但配置环境时会变麻烦。
